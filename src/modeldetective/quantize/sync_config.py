"""Write manifest facts (files, SHA256, bits/weight, revisions) into configs/models.yaml.

The YAML is the human-readable pin; the manifests are the source of truth. Run after the pipeline:
    uv run python -m modeldetective.quantize.sync_config
"""

from __future__ import annotations

import json
from pathlib import Path

import yaml

CONFIG = Path("configs/models.yaml")


def main() -> None:
    cfg = yaml.safe_load(CONFIG.read_text(encoding="utf-8"))
    changed = 0
    for key, m in cfg["models"].items():
        mdir = Path("models") / key
        rev = mdir / "hf" / ".revision"
        if rev.exists():
            m["hf_revision"] = rev.read_text().strip()
        mans = sorted((mdir / "manifests").glob("*.json")) if (mdir / "manifests").exists() else []
        if not mans:
            continue
        m.setdefault("local_dir", f"models/{key}")
        m["variants"] = {}
        for p in mans:
            man = json.loads(p.read_text(encoding="utf-8"))
            entry = {
                "file": man["file"],
                "sha256": man["sha256"],
                "bpw": man.get("bpw_from_size"),
                "made_with": f"{'convert_hf_to_gguf --outtype f16' if man['kind'] == 'reference' else 'llama-quantize ' + man['kind']} ({man['llama_cpp_build']})",
            }
            if man["kind"] == "reference":
                m["reference"] = entry
            else:
                m["variants"][man["kind"]] = entry
            changed += 1
    CONFIG.write_text(
        "# Models used in this project. Pin everything. Never commit the weights themselves.\n"
        "# Generated by modeldetective.quantize.sync_config from the local manifests; edit notes by hand,\n"
        "# never the hashes. license_ok: whether publishing results is permitted under the model license.\n\n"
        + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True, width=120),
        encoding="utf-8",
        newline="\n",
    )
    print(f"updated {CONFIG} with {changed} manifest entries")


if __name__ == "__main__":
    main()
